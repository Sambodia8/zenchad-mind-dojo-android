import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const source = (file) => fs.readFileSync(path.join(root, file), "utf8").replace(/\r\n/g, "\n");

const plugin = source("android/app/src/main/java/com/zenchad/minddojo/RunningPhotosPlugin.java");
const manifest = source("android/app/src/main/AndroidManifest.xml");
const runtime = source("src/runningPhotoRuntime.ts");
const screen = source("src/screens/RunningModeScreen.tsx");
const gallery = source("src/components/RunPhotoGallery.tsx");

assert.match(manifest, /READ_MEDIA_IMAGES/);
assert.match(manifest, /READ_MEDIA_VISUAL_USER_SELECTED/);
assert.doesNotMatch(manifest, /MANAGE_EXTERNAL_STORAGE/);
assert.match(plugin, /imagesSelected/);
assert.match(plugin, /READ_MEDIA_VISUAL_USER_SELECTED/);
assert.match(plugin, /DATE_ADDED.*>= \?/s, "MediaStore scan must use an incremental lower bound");
assert.match(plugin, /capturedAt < startedAt - START_GRACE_MS/);
assert.match(plugin, /capturedAt > now \+ FUTURE_GRACE_MS/, "future-dated camera metadata must not enter a run");
assert.match(plugin, /DATE_ADDED[\s\S]*?\* 1000L/, "DATE_ADDED seconds must be converted to epoch milliseconds");
assert.match(plugin, /DATE_TAKEN/);
assert.match(plugin, /permissionName\(\)/, "Android photo access must distinguish full and selected-only access");
assert.match(plugin, /return "limited"/, "selected-only Android access must never be reported as full access");
assert.match(plugin, /state == PermissionState\.PROMPT \? "prompt" : "denied"/, "a re-requestable Android denial must be reported as denied, not as a fresh prompt");
assert.match(plugin, /updateMetadata/, "native photo metadata must be updateable after later GPS points arrive");
assert.match(plugin, /moveAssociation/, "native photo associations must move atomically between completed runs");
assert.match(plugin, /noBackupFilesDir/, "thumbnail storage must stay outside backup data");
assert.match(plugin, /loadThumbnail/, "only a bounded thumbnail should be copied");
assert.match(plugin, /getDisplayDataUrl/, "the gallery needs an on-demand display rendition");
assert.match(plugin, /findPhoto\(runId, id\)/, "display requests must resolve a saved association instead of trusting a web-provided URI");
assert.match(plugin, /Math\.min\(2_048/, "display decoding must have a hard size bound");
assert.match(plugin, /ImageDecoder\.decodeBitmap/, "modern Android must decode orientation-aware display images");
const displayMethod = plugin.slice(plugin.indexOf("public void getDisplayDataUrl"), plugin.indexOf("private String[] projection"));
assert.doesNotMatch(displayMethod, /FileOutputStream/, "gallery display images must not be persisted as full-size app copies");
assert.match(plugin, /seen\.contains\(id\)/, "refresh must deduplicate already-associated MediaStore rows");
assert.match(plugin, /sourceExists/, "deleted source images must be surfaced as unavailable rather than crashing");
assert.match(runtime, /window\.clearInterval\(timer\)/, "polling must clean up its timer");
assert.match(runtime, /if \(stopped\) return null/, "a stopped poll must not deliver a late callback");
assert.match(screen, /startActiveRunPhotoPolling/, "measured runs must start the foreground photo poller");
assert.match(runtime, /Math\.abs\(point\.at - photo\.capturedAt\)/, "photos must match the recorded GPS point nearest capture time");
assert.match(runtime, /updateRunPhotoMetadata/, "later native GPS points must be able to improve an earlier photo match");
assert.match(screen, /getRunPoints: \(\) => loadRunSession\(\)\?\.points/, "photo matching must use all accepted measured-run points");
assert.match(screen, /await syncRunningNativePoints\(\);[\s\S]*?photoPoller\.current\?\.refresh\(\)/, "camera resume must synchronise native GPS before immediately refreshing photos");
assert.match(screen, /await photoPoller\.current\?\.refresh\(\)/, "finishing a run must perform a final photo scan");
assert.match(screen, /Selected photos only/, "limited access must be described honestly in the active-run UI");
assert.match(screen, /Manage access/, "selected-only access must remain discoverable from the active run");
assert.match(screen, /Optional caption/, "history must support a friendly local photo caption");
assert.match(screen, /moveRunPhotoAssociation/, "history must support moving a photo to another completed run");
assert.doesNotMatch(screen, /photo\.displayName/, "raw camera filenames must not be shown as the normal photo label");
assert.match(screen, /removeRunPhotoAssociation/, "history must let a runner remove a run-photo association");
assert.match(screen, /deleteRunPhotoAppCopy/, "history must let a runner delete only ZenChad's thumbnail copy");
assert.match(screen, /Original remains in your camera library/, "the UI must make camera-library ownership explicit");
assert.match(screen, /RunPhotoGallery/, "run history must open an in-app photo gallery");
assert.match(gallery, /left\.capturedAt - right\.capturedAt/, "gallery photos must follow capture order");
assert.match(gallery, /onPointerDown/, "gallery must support touch swiping");
assert.match(gallery, /getRunPhotoThumbnailDataUrl/, "gallery must fall back to the private thumbnail when the original is unavailable");

console.log("Running photo source tests passed.");
